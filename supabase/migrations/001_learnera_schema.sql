       (select count(*) from public.live_session_participants p where p.session_id = ls.id) as participants_count
  from public.live_sessions ls
  left join public.courses c on c.id = ls.course_id
  left join public.users u on u.id = ls.host_id;

create or replace view public.app_live_participants
with (security_invoker = true) as
select p.*, u.name as user_name, u.email as user_email, u.photo as user_photo, u.role as user_role
  from public.live_session_participants p
  left join public.users u on u.id = p.user_id;

create or replace view public.app_certificates
with (security_invoker = true) as
