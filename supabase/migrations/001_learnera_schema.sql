create or replace function public.replace_staff_courses(p_user_id bigint, p_course_ids bigint[])
returns void language plpgsql security invoker set search_path = public as $$
begin
  delete from public.staff_courses where user_id = p_user_id;
  insert into public.staff_courses (user_id, course_id)
  select p_user_id, x from unnest(coalesce(p_course_ids, '{}'::bigint[])) as x
  on conflict (user_id, course_id) do nothing;
end;
$$;

create or replace function public.sync_course_days(p_course_id bigint, p_dates date[])
returns void language plpgsql security invoker set search_path = public as $$
begin
  delete from public.course_days
   where course_id = p_course_id
     and not (day_date = any(coalesce(p_dates, '{}'::date[])));
  insert into public.course_days (course_id, day_date, position)
  select p_course_id, d, ordinality - 1
    from unnest(coalesce(p_dates, '{}'::date[])) with ordinality as dates(d, ordinality)
  on conflict (course_id, day_date) do update set position = excluded.position;
end;
$$;

create or replace function public.create_assignment_with_files(
  p_course_id bigint, p_title text, p_description text, p_due_date date,
  p_max_grade integer, p_files jsonb
) returns bigint language plpgsql security invoker set search_path = public as $$
declare
  new_id bigint;
begin
  insert into public.assignments (course_id, title, description, due_date, max_grade)
  values (p_course_id, p_title, p_description, p_due_date, p_max_grade)
  returning id into new_id;

  insert into public.assignment_files (assignment_id, stored_name, original_name, mime, size)
  select new_id, f->>'storedName', f->>'originalName', nullif(f->>'mime', ''),
         coalesce(nullif(f->>'size', '')::bigint, 0)
    from jsonb_array_elements(coalesce(p_files, '[]'::jsonb)) as f;
  return new_id;
end;
$$;

create or replace function public.create_live_session(
  p_course_id bigint, p_host_id bigint, p_title text, p_room_key text
) returns bigint language plpgsql security invoker set search_path = public as $$
declare
  new_id bigint;
begin
  update public.live_sessions
     set status = 'ended', ended_at = now()
   where course_id = p_course_id and status = 'live';
  insert into public.live_sessions (course_id, host_id, title, status, room_key)
  values (p_course_id, p_host_id, coalesce(p_title, ''), 'live', p_room_key)
  returning id into new_id;
  return new_id;
end;
$$;

create or replace function public.reset_identity_sequences()
returns void language plpgsql security invoker set search_path = public as $$
declare
  t text;
  seq text;
  max_id bigint;
begin
  foreach t in array array[
    'courses', 'course_days', 'users', 'attendance', 'assignments',
    'assignment_files', 'submissions', 'submission_files', 'activity_logs',
    'announcements', 'course_files', 'live_sessions',
    'live_session_participants', 'live_session_events', 'certificates'
  ] loop
    seq := pg_get_serial_sequence('public.' || t, 'id');
    if seq is not null then
      execute format('select coalesce(max(id), 0) from public.%I', t) into max_id;
      perform setval(seq, greatest(max_id, 1), max_id > 0);
    end if;
  end loop;
end;
$$;

