  from public.course_files f
  left join public.users u on u.id = f.uploaded_by;

create or replace view public.app_live_sessions
with (security_invoker = true) as
select ls.*, c.name as course_name, u.name as host_name, u.role as host_role, u.photo as host_photo
  from public.live_sessions ls
