-- LearnEra schema for Supabase Postgres.
-- Backend access uses the service role key; RLS keeps tables private to clients.

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  location_type text check (location_type is null or location_type in ('online', 'offline')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.course_days (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  day_date date not null,
  position integer not null default 0,
  unique (course_id, day_date)
);

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null,
  email_normalized text generated always as (lower(email)) stored,
  password_hash text not null,
  name text not null default '',
  role text not null default 'user' check (role in ('user', 'instructor', 'coordinator', 'admin')),
  photo text,
  student_id text,
  student_id_normalized text generated always as (lower(student_id)) stored,
  course_id bigint references public.courses(id) on delete set null,
  language text not null default 'en' check (language in ('ar', 'en')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists idx_users_email_lower on public.users (lower(email));
create unique index if not exists idx_users_student_id_lower
  on public.users (lower(student_id)) where student_id is not null;

create table if not exists public.staff_courses (
  user_id bigint not null references public.users(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, course_id)
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  course_day_id bigint not null references public.course_days(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  present smallint not null default 0 check (present in (0, 1)),
  updated_at timestamptz not null default now(),
  unique (course_day_id, user_id)
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  title text not null,
  description text,
  due_date date not null,
  max_grade integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.assignment_files (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  stored_name text not null,
  original_name text not null,
  mime text,
  size bigint not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  submitted_at timestamptz not null default now(),
  is_late smallint not null default 0 check (is_late in (0, 1)),
  grade numeric,
  feedback text,
  graded_at timestamptz,
  graded_by bigint references public.users(id) on delete set null,
  unique (assignment_id, user_id)
);

create table if not exists public.submission_files (
  id bigint generated by default as identity primary key,
  submission_id bigint not null references public.submissions(id) on delete cascade,
  stored_name text not null,
  original_name text not null,
  mime text,
  size bigint not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on delete set null,
  action text not null,
  entity text,
  entity_id bigint,
  details text,
  ip text,
  created_at timestamptz not null default now()
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  author_id bigint references public.users(id) on delete set null,
  title text not null,
  body text not null default '',
  publish_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.announcement_reads (
  announcement_id bigint not null references public.announcements(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  read_at timestamptz not null default now(),
  primary key (announcement_id, user_id)
);

create table if not exists public.course_files (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  uploaded_by bigint references public.users(id) on delete set null,
  stored_name text not null,
  original_name text not null,
  mime text,
  size bigint not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.live_sessions (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  host_id bigint not null references public.users(id) on delete cascade,
  title text not null default '',
  status text not null default 'live' check (status in ('live', 'ended')),
  room_key text not null,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  host_joined_at timestamptz,
  host_left_at timestamptz
);
create index if not exists idx_live_sessions_course on public.live_sessions(course_id, status);
create unique index if not exists idx_live_sessions_one_live_per_course
  on public.live_sessions(course_id) where status = 'live';

create table if not exists public.live_session_participants (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.live_sessions(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  is_host smallint not null default 0 check (is_host in (0, 1)),
  publisher smallint not null default 0 check (publisher in (0, 1)),
  joined_at timestamptz not null default now(),
  left_at timestamptz,
  duration_secs integer not null default 0,
  mic_opens integer not null default 0,
  mic_secs integer not null default 0,
  unique (session_id, user_id)
);

create table if not exists public.live_session_events (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.live_sessions(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  event text not null,
  at timestamptz not null default now()
);
create index if not exists idx_live_events_session on public.live_session_events(session_id, id);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  course_id bigint references public.courses(id) on delete set null,
  title text not null,
  body text,
  issued_date date not null,
  created_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists idx_certificates_user on public.certificates(user_id);

create or replace view public.app_users_with_stats
with (security_invoker = true) as
select u.*,
       c.name as course_name,
       (select count(*) from public.course_days cd where cd.course_id = u.course_id) as total_days,
       (select count(*) from public.attendance a
          join public.course_days cd2 on cd2.id = a.course_day_id
         where a.user_id = u.id and a.present = 1 and cd2.course_id = u.course_id) as attended,
       (select count(*) from public.course_days cd3
         where cd3.course_id = u.course_id and cd3.day_date < current_date
           and not exists (
             select 1 from public.attendance a3
              where a3.course_day_id = cd3.id and a3.user_id = u.id and a3.present = 1
           )) as absent,
       (select string_agg(sc.course_id::text, ',' order by sc.course_id)
          from public.staff_courses sc where sc.user_id = u.id) as taught_ids
  from public.users u
  left join public.courses c on c.id = u.course_id;

create or replace view public.app_courses_with_stats
with (security_invoker = true) as
select c.*,
       (select count(*) from public.course_days cd where cd.course_id = c.id) as days_count,
       (select count(*) from public.users u where u.course_id = c.id) as students_count,
       (select count(*) from public.users u where u.course_id = c.id and u.role = 'user') as enrolled_students_count,
       (select count(*) from public.assignments a where a.course_id = c.id) as assignments_count
  from public.courses c;

create or replace view public.app_staff_courses
with (security_invoker = true) as
select sc.user_id, c.*,
       (select count(*) from public.users u where u.course_id = c.id and u.role = 'user') as students_count,
       (select count(*) from public.assignments a where a.course_id = c.id) as assignments_count,
       (select count(*) from public.course_days cd where cd.course_id = c.id) as days_count
  from public.staff_courses sc
  join public.courses c on c.id = sc.course_id;

create or replace view public.app_assignments_with_stats
with (security_invoker = true) as
select a.*, c.name as course_name,
       (select count(*) from public.assignment_files af where af.assignment_id = a.id) as files_count,
       (select count(*) from public.submissions s where s.assignment_id = a.id) as submissions_count,
       (select count(*) from public.submissions s where s.assignment_id = a.id and s.grade is not null) as graded_count
  from public.assignments a
  left join public.courses c on c.id = a.course_id;

create or replace view public.app_submissions
with (security_invoker = true) as
select s.*, u.name as student_name, u.email as student_email, u.photo as student_photo
  from public.submissions s
  join public.users u on u.id = s.user_id;

create or replace view public.app_announcements
with (security_invoker = true) as
